drop policy if exists message_reads_member on public.message_reads;
create policy message_reads_member on public.message_reads
for select to authenticated
using (
  exists (
    select 1
    from public.messages m
    where m.id = message_reads.message_id
      and private.is_conversation_member(m.conversation_id)
  )
);
