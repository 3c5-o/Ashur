drop policy if exists saved_reels_own on public.saved_reels;
create policy saved_reels_own on public.saved_reels
for all to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

drop policy if exists story_views_read on public.story_views;
create policy story_views_read on public.story_views
for select to authenticated
using (
  user_id = (select auth.uid())
  or exists (
    select 1 from public.stories s
    where s.id = story_views.story_id
      and s.author_id = (select auth.uid())
  )
);

drop policy if exists story_views_insert on public.story_views;
create policy story_views_insert on public.story_views
for insert to authenticated
with check (
  user_id = (select auth.uid())
  and exists (select 1 from public.stories s where s.id = story_views.story_id)
);

drop policy if exists support_tickets_own_read on public.support_tickets;
create policy support_tickets_own_read on public.support_tickets
for select to authenticated
using (user_id = (select auth.uid()));

drop policy if exists support_tickets_own_insert on public.support_tickets;
create policy support_tickets_own_insert on public.support_tickets
